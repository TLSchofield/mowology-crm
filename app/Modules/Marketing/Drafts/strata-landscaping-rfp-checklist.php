<p><strong>Quick answer:</strong> a strata landscaping RFP should describe the property in measurable terms, list every service with a frequency and a month, state how work will be proven, set the winter response terms, and name the insurance and safety documents you expect. Do that and the quotes you get back will be comparable. Skip it and the cheapest quote is usually the one that left the most out.</p>

<h2>Why most strata landscaping tenders go wrong</h2>
<p>Under the BC Strata Property Act the strata corporation is responsible for repairing and maintaining common property, and landscaping is usually its largest recurring contract. Yet the typical request is a one-line email: "please quote weekly landscaping maintenance." Every contractor fills the gaps differently, the council compares numbers that describe different jobs, and the disputes start in the first summer. The checklist below fixes that at the tender stage.</p>

<h2>1. Describe the property, not the job</h2>
<ul>
<li>Civic address, number of units and buildings, and a site plan if you have one.</li>
<li>Approximate lawn area, and whether it is level, sloped or terraced.</li>
<li>Length and height of hedges, and the species if known (laurel, cedar and boxwood behave very differently).</li>
<li>Number and rough size of garden beds; whether they are mulched.</li>
<li>Trees on common property, especially large deciduous trees that drive the fall leaf load.</li>
<li>Hard surfaces the crew is expected to keep clean: walkways, visitor parking, entrances, stairs.</li>
<li>Irrigation: present or not, and who maintains it.</li>
<li>Access: gates, codes, parking for a crew truck, and any hours when noise is restricted.</li>
</ul>

<h2>2. List every service with a frequency and a month</h2>
<p>This is the section that makes quotes comparable. A useful format is a table of service, frequency and season. At minimum cover:</p>
<ul>
<li>Mowing and edging: weekly March to October, bi-weekly November to February is typical on the coast.</li>
<li>Bed maintenance: weeding, deadheading, cutting back, on rotation through the growing season.</li>
<li>Hedge and shrub trimming: how many times a year, and whether height reduction is in scope.</li>
<li>Spring cleanup and fall cleanup as named events, with the fall leaf program specified as one visit or several.</li>
<li>Lawn treatments: aeration, overseeding, lime, fertilizer, moss control, and whether they are included or priced as extras.</li>
<li>Hard-surface blowing and litter pickup on every visit.</li>
<li>Drain and catch-basin clearing during the fall program.</li>
<li>Green-waste disposal included, or billed.</li>
</ul>

<h2>3. Say how work will be proven</h2>
<p>Councils rarely inspect, and property managers cannot be on site weekly. Ask each bidder how they document a visit. The answer you want is time-stamped photos after every visit, sent to a named contact, with a way to raise an issue that gets a reply. A contractor who cannot show you last week's photos on another property will not be able to show you yours.</p>

<h2>4. Set the winter terms separately</h2>
<p>Snow and ice is where liability lives. Specify:</p>
<ul>
<li>Which areas are cleared first (entrances, stairs and walkways before parking).</li>
<li>What triggers a salting visit: forecast freeze, not only snowfall, because most Vancouver slip hazards are refrozen thaw.</li>
<li>Response expectations during a multi-day event, and whether repeat visits are included.</li>
<li>Documentation: a time-stamped log and photos of every clearing and salting visit, kept and available to the council. Municipal bylaws in Vancouver require sidewalks bordering a property to be cleared by 10 a.m. the morning after snowfall; your contract should be written to meet that.</li>
</ul>

<h2>5. Ask for the paperwork before you compare prices</h2>
<ul>
<li>Certificate of commercial general liability insurance, with the limit stated. $5 million is common for strata work.</li>
<li>WorkSafeBC clearance letter, current.</li>
<li>Business licence for the municipality.</li>
<li>Names of two or three comparable strata properties they maintain, with permission to contact the council or manager.</li>
<li>Who will actually be on site: a dedicated crew, or whoever is available that day.</li>
</ul>

<h2>6. Decide the commercial terms up front</h2>
<ul>
<li>Contract length (one year with renewal is typical) and notice period.</li>
<li>Monthly flat fee versus per-visit billing, and whether the fee is level across the year or seasonal.</li>
<li>How extras are approved and priced: storm damage, plant replacement, irrigation repair, resident requests.</li>
<li>Whether the contractor attends an AGM or council meeting on request.</li>
<li>Start date, and whether a spring cleanup is needed to bring the property to standard before regular service begins.</li>
</ul>

<h2>7. Compare the quotes on scope first, price second</h2>
<p>Lay the quotes side by side against your service list. Mark anything missing, anything priced as an extra, and anything vaguer than your RFP. A quote that is 15 percent cheaper but excludes the fall leaf program, hedge trims and green-waste disposal is not cheaper. Only when the scopes match should price decide.</p>

