#!/usr/bin/env node
// scripts/ittai-css-tokens.mjs — Ittai v1.2 design tokens → web CSS custom properties for the CRM.
// Reads docs/design/ittai-v1.2/tokens.json (+ tenants.generated.json) — the same source as the iOS
// generator (scripts/ittai-swift-tokens.mjs on feature/language). Writes public/crm/css/ittai-tokens.css.
// Every property is prefixed --it-* and scoped to .it-design (and a body that contains it, so the page
// background can use them), so nothing changes on a page until
// that class is present. Light only for now (the CRM shell has no dark mode yet).
//   node scripts/ittai-css-tokens.mjs [tenant]      (default: mowology)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'docs/design/ittai-v1.2');
const tokens = JSON.parse(readFileSync(join(dir, 'tokens.json'), 'utf8'));
const tenants = JSON.parse(readFileSync(join(dir, 'tenants.generated.json'), 'utf8'));
const tenantId = process.argv[2] || 'mowology';
const tenant = tenants[tenantId];
if (!tenant) { console.error(`unknown tenant ${tenantId}`); process.exit(1); }

const theme = 'light';
const lines = [];
for (const t of tokens.color.tokens) {
  // A string value is a reference to another token, e.g. "{status-progress}" → var(--it-status-progress).
  const ref = typeof t.value === 'string' && t.value.match(/^\{([a-z0-9-]+)\}$/);
  const v = ref ? `var(--it-${ref[1]})` : (tenant[theme][t.name] ?? t.value[theme]);
  if (v) lines.push(`--it-${t.name}:${v}`);
}
for (const [k, v] of Object.entries(tenant[theme])) {
  if (!lines.some(l => l.startsWith(`--it-${k}:`))) lines.push(`--it-${k}:${v}`);
}
for (const group of ['spacing', 'radius', 'stroke', 'size']) {
  for (const t of tokens[group].tokens) lines.push(`--it-${t.name}:${t.value}`);
}
for (const t of tokens.shadow.tokens) lines.push(`--it-${t.name}:${t.value[theme]}`);
for (const [k, v] of Object.entries(tokens.type.families)) lines.push(`--it-font-${k}:${v}`);
for (const g of tokens.type.groups) for (const s of g.styles) {
  lines.push(`--it-${s.name}-size:${s.fontSize}`, `--it-${s.name}-line:${s.lineHeight}`, `--it-${s.name}-weight:${s.fontWeight}`);
}

const out = `/* Ittai v${tokens.version} tokens (${theme}, tenant "${tenantId}") — GENERATED by scripts/ittai-css-tokens.mjs from docs/design/ittai-v1.2. Do not edit. */\n` +
  `.it-design,body:has(.it-design){\n  ${lines.join(';\n  ')};\n}\n`;
writeFileSync(join(root, 'public/crm/css/ittai-tokens.css'), out);
console.log(`wrote public/crm/css/ittai-tokens.css (${lines.length} tokens)`);
