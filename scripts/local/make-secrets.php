<?php
/**
 * LOCAL TEST ONLY — write public/app_config/secrets.php for the local test site.
 *
 *   php scripts/local/make-secrets.php <db_name> <db_user> <db_pass> <db_port>
 *
 * Every internal secret is random. Every external service (SMTP, Stripe, Anthropic, APNs, FCM,
 * Google, Trackimo, Meta, IMAP, OCR) is blank or an obvious fake so any call fails fast and
 * nothing can reach a real service. Refuses to overwrite a secrets.php that is not one of ours.
 */
declare(strict_types=1);

if ($argc < 5) { fwrite(STDERR, "usage: make-secrets.php <db> <user> <pass> <port>\n"); exit(2); }
[$_, $dbName, $dbUser, $dbPass, $dbPort] = $argv;

$path = dirname(__DIR__, 2) . '/public/app_config/secrets.php';
if (is_file($path)) {
    $head = (string)file_get_contents($path, false, null, 0, 400);
    if (strpos($head, 'LOCAL TEST ONLY') === false) {
        fwrite(STDERR, "REFUSING: $path exists and is not a LOCAL TEST ONLY file.\n");
        exit(1);
    }
}

$r = fn(int $bytes = 32): string => bin2hex(random_bytes($bytes));
$e = fn(string $s): string => var_export($s, true);

$php = <<<PHP
<?php
// =====================================================================================
//  LOCAL TEST ONLY — generated by scripts/local/make-secrets.php on {$e(date('c'))}
//  NOT production. NEVER upload this file. It is gitignored (public/app_config/secrets.php).
//  Internal secrets are random; every external service is blank or fake on purpose so
//  nothing here can send mail, charge a card, push to a phone or call a paid API.
// =====================================================================================

define('APP_ENV', 'dev');
define('APP_DEBUG', true);
define('LOCAL_TEST_SITE', true);

// Local MySQL (scripts/local-site.sh). 'localhost' = the unix socket that local-site.sh sets via
// pdo_mysql.default_socket / mysqli.default_socket (the server also listens on 127.0.0.1:{$dbPort}).
define('DB_HOST', 'localhost');
define('DB_NAME', {$e($dbName)});
define('DB_USER', {$e($dbUser)});
define('DB_PASS', {$e($dbPass)});
define('DB_CHARSET', 'utf8mb4');

// Internal secrets — random per install.
define('BLUEMOON_JWT_SECRET', {$e($r())});
define('UNSUBSCRIBE_SECRET', {$e($r())});
define('CMS_PREVIEW_SECRET', {$e($r())});
define('TRACKING_SECRET', {$e($r())});
define('APP_ENCRYPTION_KEY', {$e($r())});
define('SOCIAL_ENCRYPTION_KEY', {$e(base64_encode(random_bytes(32)))});
define('SALES_TEXT_BRIDGE_TOKEN', {$e($r())});
define('SALES_POLL_KEY', {$e($r(16))});
define('ICLOUD_POLL_KEY', {$e($r(16))});
define('INDEXNOW_KEY', {$e($r(16))});
define('CLAUDE_CONTEXT_TOKEN', {$e($r())});

// Email: NO SMTP. Blank host => MessagingService falls back to mail(), and php.ini's
// sendmail_path points at scripts/local/sendmail-log.sh, which only appends to a log file.
// SMTP_USER/SMTP_PASS stay undefined so no IMAP mailbox (MailboxConfig) is ever "configured".
define('SMTP_HOST', '');
define('SMTP_PORT', 0);

// External services — blank / fake. Stripe with an empty key throws before any request.
define('STRIPE_SECRET_KEY', '');
define('STRIPE_PUBLISHABLE_KEY', 'pk_test_LOCAL_FAKE_NOT_A_REAL_KEY');
define('STRIPE_WEBHOOK_SECRET', 'whsec_LOCAL_FAKE');
define('ANTHROPIC_API_KEY', '');
define('GOOGLE_MAPS_API_KEY', 'LOCAL-FAKE-MAPS-KEY');
define('GOOGLE_GEOCODING_KEY', '');
define('GOOGLE_CLIENT_ID', '');
define('GOOGLE_CLIENT_SECRET', '');
define('GOOGLE_REDIRECT_URI', 'http://localhost:8000/invalid-local');
define('META_APP_ID', '');
define('META_APP_SECRET', '');
define('OCR_SPACE_API_KEY', '');
define('RECAPTCHA_V3_SITE_KEY', '');
define('RECAPTCHA_V3_SECRET_KEY', '');
define('RECAPTCHA_V2_SITE_KEY', '');
define('RECAPTCHA_V2_SECRET_KEY', '');
define('TRACKIMO_CLIENT_ID', '');
define('TRACKIMO_CLIENT_SECRET', '');
// Deliberately UNDEFINED: APNS_*, FCM_*, GOOGLE_VISION_CREDENTIALS, GSC_SERVICE_ACCOUNT_JSON,
// TRACKIMO_USERNAME/PASSWORD/DEVICE_ID, SMTP_USER/SMTP_PASS, *_IMAP_PASS, ICLOUD_IMAP_*.
PHP;

if (!is_dir(dirname($path))) mkdir(dirname($path), 0700, true);
file_put_contents($path, $php . "\n");
chmod($path, 0600);
echo "wrote $path\n";
