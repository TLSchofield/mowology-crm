// Ittai v1.2 — build tokens.css from tokens.json + tenant.config.json. Precedence (proven by tests/precedence): field > explicit theme > OS > light.
// usage: node build-tokens.mjs [tenantId]  → docs/design/ittai-v1.2/tokens.css   (exit 1 if a generated tenant pairing fails)
import { readFileSync, writeFileSync } from 'node:fs'; import { dirname, resolve } from 'node:path'; import { fileURLToPath } from 'node:url';
import { deriveTenant } from './derive-tenant.mjs';
const here = dirname(fileURLToPath(import.meta.url)), W = resolve(here, '../../docs/design/ittai-v1.2');
const T = JSON.parse(readFileSync(W + '/tokens.json', 'utf8')), C = JSON.parse(readFileSync(W + '/tenant.config.json', 'utf8'));
const theme = (tok, th) => { const v = tok.value; return typeof v === 'string' ? v : (v[th] ?? v.light); };
const ref = (v, th, seen = 0) => { const m = /^\{(.+)\}$/.exec(v); if (!m || seen > 8) return v; const t = T.color.tokens.find(x => x.name === m[1]); return ref(theme(t, th), th, seen + 1); };
const block = th => T.color.tokens.filter(t => !t.name.startsWith('tenant') && t.name !== 'on-tenant').map(t => `--${t.name}:${ref(theme(t, th), th)};`).join('');
export function tenantVars(id) {
  const cfg = C.tenants[id]; const d = deriveTenant(cfg.brand); if (!d.ok) throw new Error('tenant ' + id + ' fails contrast');
  const primary = cfg.pin?.primary ?? d.strong;
  return { light: { tenant: primary, 'on-tenant': '#FFFFFF', 'tenant-mark': d.markLight, 'tenant-soft': d.softLight },
           dark: { tenant: d.bright, 'on-tenant': '#0F1512', 'tenant-mark': d.markDark, 'tenant-soft': d.softDark },
           field: { tenant: primary, 'on-tenant': '#FFFFFF', 'tenant-mark': d.markLight, 'tenant-soft': d.softLight }, checks: d.checks };
}
const css = id => { const v = tenantVars(id), tv = th => Object.entries(v[th]).map(([k, x]) => `--${k}:${x};`).join('');
  return `/* Ittai v1.2 tokens — GENERATED by scripts/ittai-design/build-tokens.mjs from tokens.json + tenant "${id}" (${C.tenants[id].brand}). Do not edit. */
:root{${block('light')}${tv('light')}color-scheme:light}
@media (prefers-color-scheme:dark){:root:not([data-theme="light"]):not([data-mode="field"]){${block('dark')}${tv('dark')}color-scheme:dark}}
:root[data-theme="dark"]:not([data-mode="field"]){${block('dark')}${tv('dark')}color-scheme:dark}
:root[data-mode="field"]{${block('field')}${tv('field')}color-scheme:light}
`; };
if (import.meta.url === `file://${process.argv[1]}`) {
  const id = process.argv[2] || C.default; writeFileSync(W + '/tokens.css', css(id));
  console.log('tokens.css for', id);
}
