#!/usr/bin/env node
// Generate ItTokens.swift from the Ittai v1.2 design tokens (docs/design/ittai-v1.2/tokens.json).
// usage: node scripts/ittai-swift-tokens.mjs [tenant]   (default tenant: mowology)
//        node scripts/ittai-swift-tokens.mjs --check     (writes nothing; exit 1 if the committed Swift differs — guards against hand edits, 2026-10-25)
// The Swift file is GENERATED — never edit it by hand. Field > chosen theme > OS > light is applied by ItPalette.
import { readFileSync, writeFileSync } from 'node:fs'; import { resolve, dirname } from 'node:path'; import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..'), src = resolve(root, 'docs/design/ittai-v1.2');
const T = JSON.parse(readFileSync(resolve(src, 'tokens.json'), 'utf8'));
const CHECK = process.argv.includes('--check');
const tenantId = process.argv.slice(2).find(a => !a.startsWith('--')) || 'mowology';
const tenants = JSON.parse(readFileSync(resolve(src, 'tenants.generated.json'), 'utf8'));
if (!tenants[tenantId]) throw new Error('unknown tenant ' + tenantId);
const themes = T.color.themes.map(t => t.id); // light, dark, field
const byName = Object.fromEntries(T.color.tokens.map(t => [t.name, t]));
const tenantVals = tenants[tenantId];
const valueOf = (name, theme, depth = 0) => {
  if (depth > 8) throw new Error('alias loop ' + name);
  if (['tenant', 'on-tenant', 'tenant-mark', 'tenant-soft'].includes(name)) return tenantVals[theme][name];
  const t = byName[name]; if (!t) throw new Error('missing token ' + name);
  let v = typeof t.value === 'string' ? t.value : (t.value[theme] ?? t.value[themes[0]]);
  const m = /^\{([^}]+)\}$/.exec(v); if (m) return valueOf(m[1], theme, depth + 1);
  if (!/^#[0-9A-Fa-f]{6}$/.test(v)) throw new Error(`${name}/${theme}: unsupported value ${v}`);
  return v.toUpperCase();
};
const camel = s => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const hex = v => '0x' + v.slice(1);
const px = v => parseFloat(String(v));
const lines = [];
lines.push('//', '//  ItTokens.swift — GENERATED by scripts/ittai-swift-tokens.mjs from docs/design/ittai-v1.2/tokens.json.', `//  Tenant: ${tenantId}. Do not edit by hand; re-run the script.`, '//', '', 'import SwiftUI', '');
lines.push('/// Ittai v1.2 colour tokens per theme (hex). Use them through `ItPalette`, never directly in views.');
lines.push('enum ItTokenHex {');
for (const th of themes) {
  lines.push(`    static let ${th}: [ItColorToken: UInt32] = [`);
  for (const t of T.color.tokens) lines.push(`        .${camel(t.name)}: ${hex(valueOf(t.name, th))},`);
  lines.push('    ]');
}
lines.push('}', '');
lines.push('/// Every colour role in the design system.', 'enum ItColorToken: String, CaseIterable {');
for (const t of T.color.tokens) lines.push(`    /// ${String(t.usage || '').replace(/\s+/g, ' ').slice(0, 160)}`, `    case ${camel(t.name)} = "${t.name}"`);
lines.push('}', '');
lines.push('/// Spacing (4 pt grid), radii and strokes, in points.', 'enum ItSpace {');
for (const t of T.spacing.tokens) lines.push(`    static let s${t.name.split('-')[1]}: CGFloat = ${px(t.value)}`);
lines.push('}', 'enum ItRadius {');
for (const t of T.radius.tokens) lines.push(`    static let ${camel(t.name.replace('radius-', ''))}: CGFloat = ${px(t.value)}`);
lines.push('}', 'enum ItStroke {');
for (const t of T.stroke.tokens) lines.push(`    static let ${camel(t.name.replace('stroke-', ''))}: CGFloat = ${px(t.value)}`);
lines.push('}', 'enum ItSize {');
for (const t of T.size.tokens) lines.push(`    static let ${camel(t.name)}: CGFloat = ${px(t.value)}`);
lines.push('}', '');
lines.push('/// The type scale: size / line height / weight (Inter).', 'enum ItTextStyle: CaseIterable {');
const styles = T.type.groups.flatMap(g => g.styles);
for (const s of styles) lines.push(`    case ${camel(s.name.replace(/-(\d+)$/, '$1'))}`);
lines.push('    var size: CGFloat { switch self {');
for (const s of styles) lines.push(`        case .${camel(s.name.replace(/-(\d+)$/, '$1'))}: return ${px(s.fontSize)}`);
lines.push('    } }', '    var lineHeight: CGFloat { switch self {');
for (const s of styles) lines.push(`        case .${camel(s.name.replace(/-(\d+)$/, '$1'))}: return ${px(s.lineHeight)}`);
lines.push('    } }', '    var weight: Int { switch self {');
for (const s of styles) lines.push(`        case .${camel(s.name.replace(/-(\d+)$/, '$1'))}: return ${s.fontWeight}`);
lines.push('    } }', '}', '');
const out = resolve(root, 'ios/MowologyCRM/MowologyCRM/Core/Design/Ittai/ItTokens.swift');
const text = lines.join('\n') + '\n';
if (CHECK) {
  if (readFileSync(out, 'utf8') !== text) { console.error('ItTokens.swift differs from tokens.json — the Swift was edited by hand, or the source is behind. Fix tokens.json, then re-run without --check.'); process.exit(1); }
  console.log('ItTokens.swift matches tokens.json'); process.exit(0);
}
writeFileSync(out, text);
console.log('wrote', out.replace(root + '/', ''), `(${T.color.tokens.length} colours × ${themes.length} themes, ${styles.length} text styles)`);
